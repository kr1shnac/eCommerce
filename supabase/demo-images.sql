-- WHAT THIS FILE WAS
--   A development-only script that set products.image_url on 28 of the 34 seed
--   products to stock photographs (CC0 / public domain, a few CC BY / BY-SA)
--   uploaded to a Storage bucket under `product-images/seed/<slug>.jpg`. A real
--   shop photographs its own shelves; this made a local/demo shop look
--   furnished. Six products deliberately kept image_url NULL — paneer, butter,
--   mustard-oil, chilli-powder, mixture-namkeen and coffee-powder — because
--   their search results were all the wrong thing, and a wrong photograph is
--   worse than a drawn one.
--
-- WHY IT IS WITHDRAWN
--   The 28 URLs were absolute, and they named the OLD hosted project
--   (`ncfjzbptbtvkjvnrwyyq`). That project was deleted on 2026-11-09 when the
--   shop was rebuilt on `argahiagpywluxpqtnpp` because its schema could not be
--   trusted — and the old hostname no longer resolves in DNS, so all 28
--   photographs are gone, not merely unreachable. Running this file anywhere —
--   on production, on a fresh project, on local Docker — would write 28
--   image_url values that render as broken images, and it would do it silently,
--   because a plain UPDATE that matches rows raises nothing.
--
--   HANDOFF.md §4.5 used to say these were "absolute URLs to the current hosted
--   project's Storage bucket". That was true when written and is false now;
--   this file is the correction, and the honest answer to "why are there no
--   product photos?" is: there were never any on the live shop, and the
--   borrowed ones no longer exist.
--
-- WHAT A SHOP ACTUALLY DOES
--   Photograph the shelf from the app: `src/app/admin/photos.tsx` (the owner's
--   Photos tab) picks or takes the picture and uploads it to THIS project's
--   `product-images` bucket through `useUploadProductPhoto()`. The photo cache
--   (`expo-image`) and the emoji fallback mean a half-photographed shelf still
--   reads correctly in both themes and both languages.
