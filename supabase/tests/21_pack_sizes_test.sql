-- =============================================================================
-- 21 · Packs, not decimals — the money invariant survives M4
--
-- Rule 9.7: a new column, constraint, view and function is not done until a test
-- proves it behaves. Register M4's first instinct was to make `quantity` a
-- numeric so loose weights could be sold. This file exists to make the rejection
-- of that approach TESTABLE, so a future session cannot "simplify" it back:
--
--   1. `quantity` is STILL an integer, and `line_total_paise` is still an exact
--      `price_paise * quantity` with no rounding anywhere. If somebody makes
--      quantity numeric, assertion 1 fails immediately.
--   2. `order_items.line_total_paise` is generated, so a fractional total cannot
--      be sent by a client even if it wanted to (the generated column wins).
--   3. `total_paise = subtotal_paise + delivery_fee_paise - discount_paise` holds
--      for a pack-priced basket, computed the ordinary way.
--   4. `products_pack_fields_agree`: a 'measure' product MUST have a pack; a
--      negative or zero pack is refused.
--   5. The product guard now freezes sold_by/pack_size/pack_unit as identity, and
--      still allows stock_qty to move with the flag.
--   6. `product_pack_options` normalises 500 g and 1 kg onto one scale (g), so
--      the app can offer "also in 1 kg" without rupee arithmetic — and the view
--      respects the caller's RLS rather than bypassing it.
--   7. The backfill parsed the seeded free-text units correctly, and left
--      genuinely piece-ish products ('1 packet', 'dozen') alone.
--
-- The most important line in this file is assertion 1. Everything else describes
-- new behaviour; assertion 1 protects the rule that was already there.
-- =============================================================================

select test_result.begin_suite('21 pack sizes');

-- -----------------------------------------------------------------------------
-- 1. THE MONEY INVARIANT. Read this first.
-- -----------------------------------------------------------------------------

-- `quantity` must still be an integer type. This is the assertion that fails the
-- day somebody makes it numeric, which is the whole reason this test exists.
select test_result.eq(
  'quantity on order_items is still an integer (Rule 1: no fractional paise)',
  (
    select data_type from information_schema.columns
     where table_schema = 'public'
       and table_name   = 'order_items'
       and column_name  = 'quantity'
  ),
  'integer'
);

select test_result.eq(
  'line_total_paise is still an integer',
  (
    select data_type from information_schema.columns
     where table_schema = 'public'
       and table_name   = 'order_items'
       and column_name  = 'line_total_paise'
  ),
  'integer'
);

-- And it must still be a GENERATED column, so a client cannot send a total at all.
select test_result.eq(
  'line_total_paise is still generated by the database',
  (
    select is_generated from information_schema.columns
     where table_schema = 'public'
       and table_name   = 'order_items'
       and column_name  = 'line_total_paise'
  ),
  'ALWAYS'
);

-- The generated expression must be the plain product, with no rounding call that
-- could disagree with place_order()'s own bigint arithmetic.
select test_result.ok(
  'the generated expression is an exact product, not a rounded one',
  (
    select generation_expression not ilike '%round%'
    from information_schema.columns
     where table_schema = 'public'
       and table_name   = 'order_items'
       and column_name  = 'line_total_paise'
  )
);

-- -----------------------------------------------------------------------------
-- 2. The columns exist and the enums are what they say
-- -----------------------------------------------------------------------------

select test_result.eq(
  'products.sold_by defaults to piece',
  (
    select column_default from information_schema.columns
     where table_schema = 'public' and table_name = 'products' and column_name = 'sold_by'
  ),
  '''piece''::product_sold_by'
);

select test_result.eq(
  'sold_by has exactly the two values the design names',
  (select string_agg(enumlabel, ',' order by enumsortorder)
     from pg_enum e join pg_type t on t.oid = e.enumtypid
    where t.typname = 'product_sold_by'),
  'piece,measure'
);

select test_result.eq(
  'pack_unit is the closed list, so g and kg can be compared',
  (select string_agg(enumlabel, ',' order by enumsortorder)
     from pg_enum e join pg_type t on t.oid = e.enumtypid
    where t.typname = 'pack_unit'),
  'g,kg,ml,l,piece'
);

-- -----------------------------------------------------------------------------
-- 3. A 'measure' product must declare its pack
-- -----------------------------------------------------------------------------

reset role;

-- A measure product with no pack is a contradiction: the app could not offer an
-- alternative size, and nothing would know what "1" of it means.
select test_result.refused(
  'a measure product with no pack_size is refused',
  $$
    insert into public.products
      (store_id, category_id, name_en, name_kn, price_paise, unit, stock_qty, sold_by)
    values
      ('00000000-0000-4000-8000-000000000001', '10000000-0000-4000-8000-000000000001',
       'Pack Test No Size', 'ಪ್ಯಾಕ್ ಟೆಸ್ಟ್', 1000, 'kg', 5, 'measure')
  $$,
  '23514'
);

select test_result.refused(
  'a measure product with a zero pack_size is refused',
  $$
    insert into public.products
      (store_id, category_id, name_en, name_kn, price_paise, unit, stock_qty, sold_by, pack_size, pack_unit)
    values
      ('00000000-0000-4000-8000-000000000001', '10000000-0000-4000-8000-000000000001',
       'Pack Test Zero', 'ಪ್ಯಾಕ್ ಟೆಸ್ಟ್', 1000, 'kg', 5, 'measure', 0, 'g')
  $$,
  '23514'
);

select test_result.refused(
  'a negative pack_size is refused',
  $$
    insert into public.products
      (store_id, category_id, name_en, name_kn, price_paise, unit, stock_qty, sold_by, pack_size, pack_unit)
    values
      ('00000000-0000-4000-8000-000000000001', '10000000-0000-4000-8000-000000000001',
       'Pack Test Negative', 'ಪ್ಯಾಕ್ ಟೆಸ್ಟ್', 1000, 'kg', 5, 'measure', -5, 'g')
  $$,
  '23514'
);

-- A measure product WITH a pack is the normal case and must be accepted.
select test_result.inserted(
  'a measure product with a real pack is accepted',
  $$
    insert into public.products
      (id, store_id, category_id, name_en, name_kn, price_paise, unit, stock_qty, sold_by, pack_size, pack_unit, sort_order)
    values
      ('e0000000-0000-4000-8000-000000000021',
       '00000000-0000-4000-8000-000000000001', '10000000-0000-4000-8000-000000000001',
       'Pack Test Rice', 'ಪ್ಯಾಕ್ ಟೆಸ್ಟ್ ಅಕ್ಕಿ', 6500, '1 kg', 20, 'measure', 1000, 'kg', 901)
  $$
);

-- A plain piece product needs no pack, and is the default.
select test_result.inserted(
  'a piece product with no pack is accepted (the default shape)',
  $$
    insert into public.products
      (id, store_id, category_id, name_en, name_kn, price_paise, unit, stock_qty, sort_order)
    values
      ('e0000000-0000-4000-8000-000000000022',
       '00000000-0000-4000-8000-000000000001', '10000000-0000-4000-8000-000000000001',
       'Pack Test Soap', 'ಪ್ಯಾಕ್ ಟೆಸ್ಟ್ ಸೋಪು', 3500, '1 piece', 15, 902)
  $$
);

-- -----------------------------------------------------------------------------
-- 4. A pack-priced basket still adds up exactly (the CHECK survives)
-- -----------------------------------------------------------------------------

-- Three 1 kg packs at ₹65 each = ₹195, plus ₹25 delivery, no discount.
-- Written the ordinary way: the client supplies line quantities and the database
-- computes everything else. If any rounding crept in, `orders_totals_add_up`
-- would refuse this insert.
reset role;

insert into public.orders
  (id, store_id, user_id, order_number, status, subtotal_paise, delivery_fee_paise,
   discount_paise, total_paise, payment_method, payment_status, delivery_address,
   placed_at, idempotency_key)
values
  ('c0000000-0000-4000-8000-000000000021',
   '00000000-0000-4000-8000-000000000001',
   (select id from public.profiles where role = 'customer' order by id limit 1),
   'KNG-T21', 'placed',
   19500, 2500, 0, 22000,
   'cod', 'pending',
   '{"erased": true}'::jsonb,
   '2020-01-15 10:00:00+05:30',
   'pack-test-order-21')
on conflict (id) do nothing;

reset role;

-- A client cannot send a line total at all: the generated column REFUSES an
-- explicit value. This is the strongest form of "a fake total cannot be sent" —
-- it is not that the server overwrites it, it is that the server will not accept
-- one. A numeric `quantity` would not change this, which is why the generated
-- column is worth protecting in a test.
select test_result.refused(
  'a client cannot send a line total at all — the generated column refuses it',
  $$
    insert into public.order_items
      (order_id, product_id, product_name_en, product_name_kn, unit, price_paise, quantity, line_total_paise)
    values
      ('c0000000-0000-4000-8000-000000000021', 'e0000000-0000-4000-8000-000000000021',
       'Pack Test Rice', 'ಪ್ಯಾಕ್ ಟೆಸ್ಟ್ ಅಕ್ಕಿ', '1 kg', 6500, 3, 0)
  $$,
  '428C9'
);

insert into public.order_items
  (id, order_id, product_id, product_name_en, product_name_kn, unit, image_url, price_paise, quantity)
values
  ('d0000000-0000-4000-8000-000000000021',
   'c0000000-0000-4000-8000-000000000021',
   'e0000000-0000-4000-8000-000000000021',
   'Pack Test Rice', 'ಪ್ಯಾಕ್ ಟೆಸ್ಟ್ ಅಕ್ಕಿ', '1 kg', null, 6500, 3)
on conflict (id) do nothing;

-- And the value the DATABASE computed is the exact product, with no rounding.
select test_result.eq(
  'the database computed 3 x 6500 = 19500 with no rounding',
  (
    select line_total_paise::text from public.order_items
     where id = 'd0000000-0000-4000-8000-000000000021'
  ),
  '19500'
);

-- And the order's own total obeys the CHECK constraint it was inserted under.
-- 19500 + 2500 - 0 = 22000 is exactly what was written, so this is a read-back
-- rather than an update: the row went in through `orders_totals_add_up` already.
select test_result.eq(
  'the order total is subtotal + delivery - discount (22000)',
  (
    select total_paise::text from public.orders
     where id = 'c0000000-0000-4000-8000-000000000021'
  ),
  '22000'
);

-- A total off by even one paisa is refused. This is the constraint that would have
-- masked a rounding bug if `quantity` had been made numeric: two roundings, a
-- paisa apart, intermittently. It must still refuse, so the guard is proved live.
-- Signed in as the admin, because `orders_guard_update` (correctly) stops a
-- customer from editing an order at all — which is a different rule, already
-- proved by test 03.
select test_result.sign_in('33333333-3333-3333-3333-333333333333');
select test_result.refused(
  'a total off by one paisa is refused, even for the owner',
  $$
    update public.orders set total_paise = 22001
     where id = 'c0000000-0000-4000-8000-000000000021'
  $$,
  '23514'
);
select test_result.sign_out();

-- -----------------------------------------------------------------------------
-- 5. The guard now freezes the pack as identity
-- -----------------------------------------------------------------------------
--
-- The admin uid is 33333333-…, as in tests 19 and 20. Signing in as the admin
-- makes `current_user_role()` return 'admin', so `update_product_from_shop()`
-- passes its own door and the row is visible to RLS.
reset role;
select test_result.sign_in('33333333-3333-3333-3333-333333333333');

-- The owner may change price, stock and on/off-shelf state.
select test_result.inserted(
  'the owner can change a price on a pack product',
  $$
    select public.update_product_from_shop(
      'e0000000-0000-4000-8000-000000000021',
      7000, 8000, 18, true, '🍚'
    )
  $$
);

-- ...but may not silently redefine what the pack IS. Changing "1 kg" to "5 kg"
-- while the price stays the same is a different product, not a price edit.
select test_result.refused(
  'the owner cannot redefine the pack size on an ordinary shelf save',
  $$
    update public.products set pack_size = 5000
     where id = 'e0000000-0000-4000-8000-000000000021'
  $$,
  '42501'
);

select test_result.refused(
  'the owner cannot change sold_by on an ordinary update',
  $$
    update public.products set sold_by = 'piece'
     where id = 'e0000000-0000-4000-8000-000000000021'
  $$,
  '42501'
);

-- The RPC cannot *clear* a measure product's pack, because `null` means "leave
-- this field alone" in this function — so the pack survives, and the product is
-- still a valid measure product. That is the honest behaviour, and it is worth
-- asserting: it is what stops the phone sending a sparse update from wiping a
-- pack by omission.
select test_result.eq(
  'a null pack argument leaves the pack alone rather than clearing it',
  (
    select (sold_by::text || '/' || pack_size::text || '/' || pack_unit::text)
      from public.update_product_from_shop(
        'e0000000-0000-4000-8000-000000000021',
        7000, 8000, 18, true, '🍚', 'measure', null, null
      )
  ),
  'measure/1000.000/kg'
);

-- ...and passing an explicit different pack IS refused, by the identity freeze.
-- This is the rule that stops a price edit from silently changing 1 kg into 5 kg.
select test_result.refused(
  'the RPC cannot redefine the pack size either',
  $$
    select public.update_product_from_shop(
      'e0000000-0000-4000-8000-000000000021',
      7000, 8000, 18, true, '🍚', 'measure', 5000, 'kg'
    )
  $$,
  '42501'
);

-- -----------------------------------------------------------------------------
-- 6. product_pack_options normalises the scale
-- -----------------------------------------------------------------------------

-- 500 g and 1 kg must land on the same scale, so the app can sort and compare
-- them. This is the query that makes "also in 1 kg" possible.
reset role;

select test_result.eq(
  '500 g and 1 kg normalise onto one scale (g)',
  (
    select string_agg(pack_in_base::text, ',' order by pack_in_base)
      from public.product_pack_options
     where name_en in ('Tomato', 'Onion')
  ),
  '500.000,1000.000'
);

-- A 500 ml pack normalises to 500 — ml shares the g/ml base scale, which is
-- correct for comparing sizes of the same liquid.
select test_result.eq(
  'a 500 ml pack normalises to 500 on the same scale',
  (
    select pack_in_base::text from public.product_pack_options
     where name_en = 'Full Cream Milk'
  ),
  '500.000'
);

-- A plain piece product must report NULL, not 0 — the app distinguishes "no pack"
-- from "a zero-size pack".
select test_result.ok(
  'a piece product reports no pack, not a zero one',
  (
    select pack_in_base is null
      from public.product_pack_options
     where name_en = 'Pack Test Soap'
  )
);

-- The view must not be a way around RLS.
select test_result.ok(
  'the view is security_invoker, so the products policy still applies',
  (
    select reloptions::text ilike '%security_invoker=true%'
      from pg_class where relname = 'product_pack_options'
  )
);

-- -----------------------------------------------------------------------------
-- 7. The backfill read the seeded free-text units correctly
-- -----------------------------------------------------------------------------

reset role;

select test_result.eq(
  'Tomato''s "500 g" became a 500 g measure pack',
  (
    select sold_by::text || '/' || pack_size::text || '/' || pack_unit::text
      from public.products where name_en = 'Tomato'
  ),
  'measure/500.000/g'
);

-- The stored pack keeps the unit the shop declared ('1 kg' stays 1 kg, not 1000 g).
-- Only the VIEW normalises for comparison — storing the converted value would lose
-- the fact that the shop writes '1 kg' on the shelf, and a later change of policy
-- could not tell those apart.
select test_result.eq(
  'Onion''s "1 kg" is stored as 1 kg, exactly as the shop wrote it',
  (
    select sold_by::text || '/' || pack_size::text || '/' || pack_unit::text
      from public.products where name_en = 'Onion'
  ),
  'measure/1.000/kg'
);

-- A product whose unit text is not a weight must be left as a plain piece —
-- nothing invented, nothing lost.
select test_result.eq(
  'a non-weight unit was left as a piece product with no pack',
  (
    select sold_by::text || '/' || coalesce(pack_size::text, 'none')
      from public.products where name_en = 'Pack Test Soap'
  ),
  'piece/none'
);

select test_result.ok(
  'no active product is a measure product without a pack',
  (
    select count(*) = 0 from public.products
     where sold_by = 'measure' and (pack_size is null or pack_unit is null)
  )
);

-- -----------------------------------------------------------------------------
-- Clean up our own fixtures (tests 19 and 20 do the same).
-- -----------------------------------------------------------------------------

reset role;

delete from public.order_items where order_id = 'c0000000-0000-4000-8000-000000000021';
delete from public.orders      where id       = 'c0000000-0000-4000-8000-000000000021';
delete from public.products    where id in (
  'e0000000-0000-4000-8000-000000000021',
  'e0000000-0000-4000-8000-000000000022'
);
